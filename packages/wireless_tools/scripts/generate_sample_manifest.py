"""Create and verify the checked-in MATLAB oracle-sample integrity manifest."""
from __future__ import annotations

import argparse
import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
ORACLE_DIR = ROOT / "matlab_oracle"
SAMPLES_DIR = ORACLE_DIR / "samples"
MANIFEST_PATH = ORACLE_DIR / "sample_manifest.json"
MANIFEST_VERSION = 1


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def describe_json(path: Path) -> dict[str, object]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if isinstance(data, list):
        root_type, entries = "array", len(data)
    elif isinstance(data, dict):
        root_type, entries = "object", len(data)
    else:
        root_type, entries = type(data).__name__, 1
    return {
        "path": path.relative_to(ORACLE_DIR).as_posix(),
        "sha256": sha256(path),
        "bytes": path.stat().st_size,
        "json_root": root_type,
        "entries": entries,
    }


def build_manifest(
    matlab_release: str,
    matlab_version: str,
    toolboxes: list[str],
    unavailable_toolboxes: list[str],
    regenerated_samples: list[str],
    static_standard_samples: list[str],
) -> dict[str, object]:
    samples = [describe_json(path) for path in sorted(SAMPLES_DIR.glob("*.json"))]
    return {
        "manifest_version": MANIFEST_VERSION,
        "generated_at_utc": datetime.now(timezone.utc).replace(microsecond=0).isoformat(),
        "oracle_baseline": {
            "matlab_release": matlab_release,
            "matlab_version": matlab_version,
            "toolboxes": sorted(toolboxes),
            "unavailable_toolboxes": sorted(unavailable_toolboxes),
            "r2026a_regenerated_samples": sorted(regenerated_samples),
            "static_standard_samples": sorted(static_standard_samples),
            "scope": (
                "Integrity inventory of checked-in JSON samples. The regenerated-sample list "
                "identifies files regenerated by the stated MATLAB baseline; static-standard "
                "samples are fixed 3GPP data rather than MATLAB output; other files retain "
                "their historical runtime provenance until regenerated."
            ),
        },
        "samples": samples,
    }


def load_manifest() -> dict[str, object]:
    return json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))


def check_manifest() -> int:
    manifest = load_manifest()
    expected = manifest.get("samples")
    if not isinstance(expected, list):
        print("FAIL sample manifest has no samples array")
        return 1

    actual = [describe_json(path) for path in sorted(SAMPLES_DIR.glob("*.json"))]
    if expected != actual:
        print("FAIL sample manifest is stale; run generate_sample_manifest.py --write")
        return 1
    print(f"PASS {len(actual)} MATLAB oracle sample files match the manifest")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write the manifest")
    mode.add_argument("--check", action="store_true", help="verify sample hashes and metadata")
    parser.add_argument("--matlab-release", default="R2026a", help="MATLAB release used as the oracle baseline")
    parser.add_argument("--matlab-version", default="26.1.0.3276743 Update 3", help="MATLAB version used as the oracle baseline")
    parser.add_argument("--toolbox", action="append", default=[], help="installed Toolbox name; repeat as needed")
    parser.add_argument(
        "--unavailable-toolbox",
        action="append",
        default=[],
        help="Toolbox required by legacy generators but absent on this oracle host; repeat as needed",
    )
    parser.add_argument(
        "--regenerated-sample",
        action="append",
        default=[],
        help="sample filename regenerated by this MATLAB baseline; repeat as needed",
    )
    parser.add_argument(
        "--static-standard-sample",
        action="append",
        default=[],
        help="fixed standard-data sample not generated by MATLAB; repeat as needed",
    )
    args = parser.parse_args()

    if args.check:
        return check_manifest()

    known_samples = {path.name for path in SAMPLES_DIR.glob("*.json")}
    unknown = sorted(set(args.regenerated_sample + args.static_standard_sample) - known_samples)
    if unknown:
        parser.error(f"unknown regenerated sample(s): {', '.join(unknown)}")
    manifest = build_manifest(
        args.matlab_release,
        args.matlab_version,
        args.toolbox,
        args.unavailable_toolbox,
        args.regenerated_sample,
        args.static_standard_sample,
    )
    MANIFEST_PATH.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"WROTE {MANIFEST_PATH.relative_to(ROOT)} ({len(manifest['samples'])} samples)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
