function gen_samples_bluetooth_outdoor_range()
%GEN_SAMPLES_BLUETOOTH_OUTDOOR_RANGE Two-ray range inversion R2026a.
requests={ ...
    struct('environment','Outdoor'), ...
    struct('environment','Outdoor','transmitter_power',20, ...
        'transmitter_antenna_height',3,'receiver_antenna_height',2), ...
    struct('environment','Outdoor','signal_power_type','ReceivedSignalPower', ...
        'received_signal_power',-50), ...
    struct('environment','Outdoor','transmitter_antenna_height',0.2, ...
        'receiver_antenna_height',0.4,'transmitter_antenna_gain',3, ...
        'receiver_antenna_gain',2), ...
    struct('environment','Outdoor','mode','LE125K', ...
        'receiver_sensitivity',-100,'link_margin',5, ...
        'transmitter_power',12,'transmitter_antenna_height',1.5, ...
        'receiver_antenna_height',0.8)};
mapping={ ...
    'environment','Environment'; ...
    'signal_power_type','SignalPowerType'; ...
    'received_signal_power','ReceivedSignalPower'; ...
    'mode','Mode'; ...
    'receiver_sensitivity','ReceiverSensitivity'; ...
    'link_margin','LinkMargin'; ...
    'transmitter_power','TransmitterPower'; ...
    'transmitter_antenna_gain','TransmitterAntennaGain'; ...
    'receiver_antenna_gain','ReceiverAntennaGain'; ...
    'transmitter_cable_loss','TransmitterCableLoss'; ...
    'receiver_cable_loss','ReceiverCableLoss'; ...
    'transmitter_antenna_height','TransmitterAntennaHeight'; ...
    'receiver_antenna_height','ReceiverAntennaHeight'};
cases=struct('request',{},'range_m',{},'path_loss_db',{},'received_power_dbm',{});
for k=1:numel(requests)
    cfg=bluetoothRangeConfig; request=requests{k};
    for n=1:size(mapping,1)
        if isfield(request,mapping{n,1})
            cfg.(mapping{n,2})=request.(mapping{n,1});
        end
    end
    [distance,pl,rx]=bluetoothRange(cfg);
    cases(k)=struct('request',request,'range_m',distance, ...
        'path_loss_db',pl,'received_power_dbm',rx);
end
fid=fopen(wt_sample_path('bluetooth_outdoor_range_samples.json'),'w','n','UTF-8');
fprintf(fid,'%s',jsonencode(cases)); fclose(fid);
end
