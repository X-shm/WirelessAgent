function gen_samples_ble_gap_data()
%GEN_SAMPLES_BLE_GAP_DATA R2026a samples for every supported AD type.
spec={ ...
    struct(); ...
    struct('AdvertisingDataTypes',{{'Flags','Tx power level'}},'LEDiscoverability','Limited','TxPowerLevel',45); ...
    struct('AdvertisingDataTypes',{{'Advertising interval','Local name'}},'AdvertisingInterval',48,'LocalNameShortening',true,'LocalName','MathWorks'); ...
    struct('AdvertisingDataTypes',{{'UUIDs'}},'Identifiers','180D','IdentifierType','Complete'); ...
    struct('AdvertisingDataTypes',{{'Connection interval range'}},'ConnectionIntervalRange',[24 40]); ...
    struct('AdvertisingDataTypes',{{'Flags'}},'LEDiscoverability','Limited and general','BREDR',true,'LE','Host')};
cases=struct('configuration',{},'data_block_hex',{},'decode_status',{});
for k=1:numel(spec)
    props=spec{k}; names=fieldnames(props); cfg=bleGAPDataBlockConfig;
    for n=1:numel(names), cfg.(names{n})=props.(names{n}); end
    data=bleGAPDataBlock(cfg); [status,~]=bleGAPDataBlockDecode(data);
    cases(k)=struct('configuration',props,'data_block_hex',reshape(data.',1,[]),'decode_status',char(status));
end
fid=fopen(wt_sample_path('ble_gap_data_samples.json'),'w','n','UTF-8'); fprintf(fid,'%s',jsonencode(cases)); fclose(fid);
end
