% Independent R2026a NPUSCH FDD data/control slot positions and info.
root = fileparts(mfilename('fullpath'));
ues = {struct('NBULSubcarrierSpacing','15kHz'),...
       struct('NBULSubcarrierSpacing','15kHz'),...
       struct('NBULSubcarrierSpacing','3.75kHz')};
channels = {struct('NPUSCHFormat','Data','NBULSubcarrierSet',0:5,...
                   'NRU',2,'NULSlots',4,'Modulation','QPSK'),...
            struct('NPUSCHFormat','Control','NBULSubcarrierSet',7,...
                   'NRU',1,'NULSlots',4,'Modulation','BPSK'),...
            struct('NPUSCHFormat','Data','NBULSubcarrierSet',33,...
                   'NRU',1,'NULSlots',16,'Modulation','BPSK')};
records = cell(1,numel(ues));
for k = 1:numel(ues)
    [positions,info] = lteNPUSCHIndices(ues{k},channels{k},{'1based','sub'});
    records{k} = struct('ue',ues{k},'channel',channels{k},...
                        'indices',double(positions),'info',info);
end
output = fullfile(root,'samples','lte_npusch_indices.json');
fid = fopen(output,'w');
fprintf(fid,'%s',jsonencode(records));
fclose(fid);
disp(output);
