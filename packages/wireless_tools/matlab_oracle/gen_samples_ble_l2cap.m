function gen_samples_ble_l2cap()
%GEN_SAMPLES_BLE_L2CAP R2026a signal and data frame oracle cases.
cases=struct('configuration',{},'sdu_hex',{},'frame_hex',{},'decode_status',{},'decoded_sdu_hex',{});
spec={ ...
    {struct('ChannelIdentifier','0004'),'0A0100'}; ...
    {struct('ChannelIdentifier','007A'),'0A01E2D3'}; ...
    {struct('ChannelIdentifier','0005','CommandType','Credit based connection request','Credits',10),''}; ...
    {struct('ChannelIdentifier','0005','CommandType','Disconnection request'),''}; ...
    {struct('ChannelIdentifier','0005','CommandType','Connection parameter update response'),''}; ...
    {struct('ChannelIdentifier','0005','CommandType','Credit based connection response'),''}; ...
    {struct('ChannelIdentifier','0005','CommandType','Flow control credit'),''}; ...
    {struct('ChannelIdentifier','0005','CommandType','Command reject','CommandRejectReason','Signaling MTU exceeded'),''}};
for k=1:numel(spec)
    item=spec{k}; props=item{1}; names=fieldnames(props); cfg=bleL2CAPFrameConfig;
    for n=1:numel(names), cfg.(names{n})=props.(names{n}); end
    sdu=item{2};
    if isempty(sdu), frame=bleL2CAPFrame(cfg); else, frame=bleL2CAPFrame(cfg,sdu); end
    [status,~,decodedSDU]=bleL2CAPFrameDecode(frame);
    cases(k)=struct('configuration',props,'sdu_hex',sdu,'frame_hex',reshape(frame.',1,[]),...
        'decode_status',char(status),'decoded_sdu_hex',reshape(decodedSDU.',1,[]));
end
fid=fopen(wt_sample_path('ble_l2cap_samples.json'),'w','n','UTF-8'); fprintf(fid,'%s',jsonencode(cases)); fclose(fid);
end
