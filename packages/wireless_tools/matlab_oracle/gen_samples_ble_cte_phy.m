function gen_samples_ble_cte_phy()
%GEN_SAMPLES_BLE_CTE_PHY R2026a LE direction-finding waveform/receiver.
spec={ ...
    struct('mode','LE1M','channel_index',36,'samples_per_symbol',8, ...
        'df_packet_type','ConnectionCTE','cte_time',2,'whiten_status','On'), ...
    struct('mode','LE2M','channel_index',37,'samples_per_symbol',4, ...
        'df_packet_type','ConnectionCTE','cte_time',3,'whiten_status','Off'), ...
    struct('mode','LE1M','channel_index',38,'samples_per_symbol',4, ...
        'df_packet_type','ConnectionlessCTE','cte_time',4,'whiten_status','On'), ...
    struct('mode','LE1M','channel_index',39,'samples_per_symbol',8, ...
        'df_packet_type','ConnectionlessCTE','cte_time',2,'whiten_status','Off'), ...
    struct('mode','LE1M','channel_index',9,'samples_per_symbol',4, ...
        'df_packet_type','ConnectionCTE','cte_time',3,'whiten_status','On', ...
        'pulse_length',2,'modulation_index',0.48)};
cases=struct('mode',{},'channel_index',{},'samples_per_symbol',{}, ...
    'df_packet_type',{},'cte_time',{},'whiten_status',{}, ...
    'pulse_length',{},'modulation_index',{},'message',{}, ...
    'waveform_real',{},'waveform_imag',{},'bits',{},'access_address',{}, ...
    'iq_real',{},'iq_imag',{});
for k=1:numel(spec)
    p=spec{k}; msg=mod((0:63)'+k,3)==0;
    if ~isfield(p,'pulse_length'), p.pulse_length=1; end
    if ~isfield(p,'modulation_index'), p.modulation_index=0.5; end
    if strcmp(p.df_packet_type,'ConnectionCTE'), start=17; pduLen=2;
    else, start=33; pduLen=3; end
    msg(9:16)=logical(int2bit(pduLen,8,false));
    msg(start:start+4)=logical(int2bit(p.cte_time,5,false));
    msg(start+5:start+7)=false;
    wave=bleWaveformGenerator(msg,'Mode',p.mode, ...
        'ChannelIndex',p.channel_index, ...
        'SamplesPerSymbol',p.samples_per_symbol, ...
        'PulseLength',p.pulse_length, ...
        'ModulationIndex',p.modulation_index, ...
        'DFPacketType',p.df_packet_type, ...
        'WhitenStatus',p.whiten_status);
    [bits,address,iq]=bleIdealReceiver(wave,'Mode',p.mode, ...
        'ChannelIndex',p.channel_index, ...
        'SamplesPerSymbol',p.samples_per_symbol, ...
        'PulseLength',p.pulse_length, ...
        'ModulationIndex',p.modulation_index, ...
        'DFPacketType',p.df_packet_type, ...
        'WhitenStatus',p.whiten_status);
    cases(k)=struct('mode',p.mode,'channel_index',p.channel_index, ...
        'samples_per_symbol',p.samples_per_symbol, ...
        'df_packet_type',p.df_packet_type,'cte_time',p.cte_time, ...
        'pulse_length',p.pulse_length,'modulation_index',p.modulation_index, ...
        'whiten_status',p.whiten_status,'message',double(msg.'), ...
        'waveform_real',real(wave).','waveform_imag',imag(wave).', ...
        'bits',double(bits.'),'access_address',double(address.'), ...
        'iq_real',real(iq).','iq_imag',imag(iq).');
end
fid=fopen(wt_sample_path('ble_cte_phy_samples.json'),'w','n','UTF-8');
fprintf(fid,'%s',jsonencode(cases)); fclose(fid);
end
