function gen_samples_bluetooth_edr_test_waveform()
%GEN_SAMPLES_BLUETOOTH_EDR_TEST_WAVEFORM RF-PHY test waveform oracle cases.
spec={ ...
    {'EDR2M','',0}; {'EDR3M','',2}; ...
    {'EDR2M','2-DH3',1}; {'EDR3M','3-EV3',5}; ...
    {'EDR2M','2-EV5',6}; {'EDR3M','3-DH5',7}};
cases=struct('mode',{},'packet_type',{},'payload_type',{}, ...
    'fixed_payload_length',{},'waveform_length',{},'sample_indices',{}, ...
    'waveform_real',{},'waveform_imag',{});
for k=1:numel(spec)
    entry=spec{k}; mode=entry{1}; packetType=entry{2}; payloadType=entry{3};
    if isempty(packetType)
        cfg=bluetoothTestWaveformConfig('Mode',mode,'PayloadType',payloadType);
    else
        cfg=bluetoothTestWaveformConfig('Mode',mode, ...
            'PacketType',packetType,'PayloadType',payloadType);
    end
    wave=bluetoothTestWaveform(cfg);
    indices=unique([1:min(1600,numel(wave)), ...
        round(linspace(1,numel(wave),512))]);
    cases(k)=struct('mode',mode,'packet_type',cfg.PacketType, ...
        'payload_type',payloadType,'fixed_payload_length',cfg.FixedPayloadLength, ...
        'waveform_length',numel(wave),'sample_indices',indices, ...
        'waveform_real',real(wave(indices)).', ...
        'waveform_imag',imag(wave(indices)).');
end
fid=fopen(wt_sample_path('bluetooth_edr_test_waveform_samples.json'),'w','n','UTF-8');
fprintf(fid,'%s',jsonencode(cases)); fclose(fid);
end
