function gen_samples_ble_ll_advertising()
%GEN_SAMPLES_BLE_LL_ADVERTISING R2026a oracle for all seven legacy LL ADV PDUs.
names = {'Advertising indication','Advertising direct indication', ...
    'Advertising non connectable indication','Scan request','Scan response', ...
    'Connection indication','Advertising scannable indication'};
extra = {struct(), struct('TargetAddress','A1B2C3D4E5F6'), ...
    struct('AdvertisingData','0303AAFE'), struct('ScannerAddress','112233445566'), ...
    struct('ScanResponseData','020A04'), ...
    struct('ConnectionInterval',8,'UsedChannels',[0 4 12 16 18 24 25], ...
        'AccessAddress','8E89BED6','SleepClockAccuracy','0 to 20 ppm'), ...
    struct('ChannelSelection','Algorithm2','AdvertisingData','')};
cases=struct('configuration',{},'pdu_hex',{},'decode_status',{});
for k=1:numel(names)
    props=extra{k}; props.PDUType=names{k};
    cfg=bleLLAdvertisingChannelPDUConfig;
    fields=fieldnames(props);
    for n=1:numel(fields), cfg.(fields{n})=props.(fields{n}); end
    bits=bleLLAdvertisingChannelPDU(cfg);
    bytes=bit2int(reshape(bits,8,[]),8,0);
    [status,~]=bleLLAdvertisingChannelPDUDecode(bits);
    cases(k)=struct('configuration',props, ...
        'pdu_hex',reshape(dec2hex(bytes,2).',1,[]), ...
        'decode_status',char(status));
end
fid=fopen(wt_sample_path('ble_ll_advertising_samples.json'),'w','n','UTF-8');
fprintf(fid,'%s',jsonencode(cases)); fclose(fid);
end
