function gen_samples_bluetooth_classic_receiver()
%GEN_SAMPLES_BLUETOOTH_CLASSIC_RECEIVER BR roundtrip R2026a golden cases.
types={'ID','NULL','POLL','FHS','DM1','DH1','HV1','HV2','HV3','AUX1', ...
    'DV','EV3','EV4','EV5','DM3','DH3','DM5','DH5'};
cases=struct('packet_type',{},'payload_length',{},'message',{}, ...
    'bits',{},'decoded_packet_type',{},'decoded_payload_length',{}, ...
    'lap',{},'packet_valid',{});
for k=1:numel(types)
    cfg=bluetoothWaveformConfig('PacketType',types{k},'Mode','BR', ...
        'DeviceAddress','0123456789AB');
    if any(strcmp(types{k},{'DM1','DH1','AUX1','DV','EV3','EV4', ...
            'EV5','DM3','DH3','DM5','DH5'})), cfg.PayloadLength=10; end
    len=getPayloadLength(cfg); message=mod((0:len*8-1)'+k,2);
    wave=bluetoothWaveformGenerator(message,cfg);
    rx=getPhyConfigProperties(cfg);
    [bits,info,valid]=bluetoothIdealReceiver(wave,rx);
    cases(k)=struct('packet_type',types{k},'payload_length',cfg.PayloadLength, ...
        'message',message.','bits',double(bits.'), ...
        'decoded_packet_type',info.PacketType, ...
        'decoded_payload_length',info.PayloadLength, ...
        'lap',info.LAP.','packet_valid',logical(valid));
end
fid=fopen(wt_sample_path('bluetooth_classic_receiver_samples.json'),'w','n','UTF-8');
fprintf(fid,'%s',jsonencode(cases)); fclose(fid);
end
