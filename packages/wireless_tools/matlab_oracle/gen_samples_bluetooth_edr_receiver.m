function gen_samples_bluetooth_edr_receiver()
%GEN_SAMPLES_BLUETOOTH_EDR_RECEIVER BR/EDR ideal-receiver golden cases.
spec={ ...
    'EDR2M','ID'; 'EDR3M','NULL'; 'EDR2M','POLL'; ...
    'EDR2M','2-DH1'; 'EDR3M','3-DH1'; ...
    'EDR2M','2-DH3'; 'EDR3M','3-DH3'; ...
    'EDR2M','2-DH5'; 'EDR3M','3-DH5'; ...
    'EDR2M','2-EV3'; 'EDR3M','3-EV3'; ...
    'EDR2M','2-EV5'; 'EDR3M','3-EV5'; ...
    'EDR2M','DM1'; 'EDR3M','FHS'; 'EDR2M','AUX1'};
cases=struct('mode',{},'packet_type',{},'payload_length',{}, ...
    'message',{},'bits',{},'decoded_packet_type',{}, ...
    'decoded_payload_length',{},'lap',{},'packet_valid',{});
for k=1:size(spec,1)
    mode=spec{k,1}; packetType=spec{k,2};
    cfg=bluetoothWaveformConfig('Mode',mode,'PacketType',packetType, ...
        'DeviceAddress','0123456789AB');
    if ~any(strcmp(packetType,{'ID','NULL','POLL'})), cfg.PayloadLength=10; end
    payloadLength=getPayloadLength(cfg);
    message=mod((0:payloadLength*8-1)'+k,2);
    wave=bluetoothWaveformGenerator(message,cfg);
    rx=getPhyConfigProperties(cfg);
    [bits,info,valid]=bluetoothIdealReceiver(wave,rx);
    cases(k)=struct('mode',mode,'packet_type',packetType, ...
        'payload_length',cfg.PayloadLength,'message',message.', ...
        'bits',double(bits.'),'decoded_packet_type',info.PacketType, ...
        'decoded_payload_length',info.PayloadLength, ...
        'lap',info.LAP.','packet_valid',logical(valid));
end
fid=fopen(wt_sample_path('bluetooth_edr_receiver_samples.json'),'w','n','UTF-8');
fprintf(fid,'%s',jsonencode(cases)); fclose(fid);
end
