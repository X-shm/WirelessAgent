% Independent R2026a sidelink MIB field and bit-position cases.
root = fileparts(mfilename('fullpath'));
configs = {struct('NSLRB',6),...
           struct('NSLRB',50),...
           struct('NSLRB',6,'DuplexMode','TDD','TDDConfig',0),...
           struct('NSLRB',6,'DuplexMode','TDD','TDDConfig',6),...
           struct('NSLRB',6,'NFrame',1),...
           struct('NSLRB',6,'NFrame',513),...
           struct('NSLRB',6,'NSubframe',1),...
           struct('NSLRB',6,'NSubframe',9),...
           struct('NSLRB',6,'InCoverage',1),...
           struct('NSLRB',20,'DuplexMode','TDD','TDDConfig',2,...
                  'NFrame',700,'NSubframe',8,'InCoverage',1)};
records = cell(1,numel(configs));
for k = 1:numel(configs)
    bits = lteSLMIB(configs{k});
    fields = lteSLMIB(bits);
    records{k} = struct('config',configs{k},'bits',double(bits(:)).',...
                        'decoded',fields);
end
output = fullfile(root,'samples','lte_sl_mib.json');
fid = fopen(output,'w');
fprintf(fid,'%s',jsonencode(records));
fclose(fid);
disp(output);
