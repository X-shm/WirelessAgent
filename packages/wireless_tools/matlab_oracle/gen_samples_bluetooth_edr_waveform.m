function gen_samples_bluetooth_edr_waveform()
%GEN_SAMPLES_BLUETOOTH_EDR_WAVEFORM R2026a EDR2M/EDR3M packet waveforms.
spec={ ...
    {'EDR2M','ID',0}; {'EDR3M','NULL',0}; {'EDR2M','POLL',0}; ...
    {'EDR2M','2-DH1',10}; {'EDR3M','3-DH1',10}; ...
    {'EDR2M','2-DH3',10}; {'EDR3M','3-DH3',10}; ...
    {'EDR2M','2-DH5',20}; {'EDR3M','3-DH5',20}; ...
    {'EDR2M','2-EV3',10}; {'EDR3M','3-EV3',10}; ...
    {'EDR2M','2-EV5',10}; {'EDR3M','3-EV5',10}; ...
    {'EDR2M','DM1',10}; {'EDR3M','FHS',18}; {'EDR2M','AUX1',1}};
cases=struct('mode',{},'packet_type',{},'payload_length',{}, ...
    'message',{},'waveform_length',{},'sample_indices',{}, ...
    'waveform_real',{},'waveform_imag',{});
for k=1:numel(spec)
    entry=spec{k}; mode=entry{1}; packetType=entry{2}; payloadLength=entry{3};
    cfg=bluetoothWaveformConfig('Mode',mode,'PacketType',packetType, ...
        'PayloadLength',payloadLength,'DeviceAddress','0123456789AB');
    len=getPayloadLength(cfg); message=mod((0:len*8-1)'+k,3)==0;
    wave=bluetoothWaveformGenerator(message,cfg);
    indices=unique([1:min(1600,numel(wave)), ...
        round(linspace(1,numel(wave),512))]);
    cases(k)=struct('mode',mode,'packet_type',packetType, ...
        'payload_length',payloadLength,'message',double(message.'), ...
        'waveform_length',numel(wave),'sample_indices',indices, ...
        'waveform_real',real(wave(indices)).', ...
        'waveform_imag',imag(wave(indices)).');
end
fid=fopen(wt_sample_path('bluetooth_edr_waveform_samples.json'),'w','n','UTF-8');
fprintf(fid,'%s',jsonencode(cases)); fclose(fid);
end
