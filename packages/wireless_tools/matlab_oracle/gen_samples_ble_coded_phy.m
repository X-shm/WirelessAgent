function gen_samples_ble_coded_phy()
%GEN_SAMPLES_BLE_CODED_PHY R2026a LE125K/LE500K waveform and RX oracle.
spec={ ...
    struct('mode','LE125K','channel_index',37,'samples_per_symbol',4, ...
        'pulse_length',1,'whiten_status','On','message_length',16), ...
    struct('mode','LE500K','channel_index',12,'samples_per_symbol',8, ...
        'pulse_length',1,'whiten_status','On','message_length',32), ...
    struct('mode','LE125K','channel_index',38,'samples_per_symbol',4, ...
        'pulse_length',2,'whiten_status','Off','message_length',40), ...
    struct('mode','LE500K','channel_index',4,'samples_per_symbol',4, ...
        'pulse_length',2,'whiten_status','Off','message_length',25), ...
    struct('mode','LE500K','channel_index',18,'samples_per_symbol',4, ...
        'pulse_length',4,'whiten_status','On','message_length',17), ...
    struct('mode','LE500K','channel_index',6,'samples_per_symbol',4, ...
        'pulse_length',2,'whiten_status','On','message_length',19, ...
        'modulation_index',0.48), ...
    struct('mode','LE125K','channel_index',20,'samples_per_symbol',4, ...
        'pulse_length',4,'whiten_status','On','message_length',18, ...
        'modulation_index',0.52), ...
    struct('mode','LE125K','channel_index',8,'samples_per_symbol',4, ...
        'pulse_length',3,'whiten_status','On','message_length',21)};
cases=struct('mode',{},'channel_index',{},'samples_per_symbol',{}, ...
    'pulse_length',{},'modulation_index',{},'whiten_status',{},'message',{}, ...
    'waveform_real',{},'waveform_imag',{},'bits',{},'access_address',{});
for k=1:numel(spec)
    p=spec{k}; msg=mod((0:p.message_length-1)'+k,3)==0;
    if ~isfield(p,'modulation_index'), p.modulation_index=0.5; end
    wave=bleWaveformGenerator(msg,'Mode',p.mode, ...
        'ChannelIndex',p.channel_index, ...
        'SamplesPerSymbol',p.samples_per_symbol, ...
        'PulseLength',p.pulse_length, ...
        'ModulationIndex',p.modulation_index, ...
        'WhitenStatus',p.whiten_status);
    [bits,address]=bleIdealReceiver(wave,'Mode',p.mode, ...
        'ChannelIndex',p.channel_index, ...
        'SamplesPerSymbol',p.samples_per_symbol, ...
        'PulseLength',p.pulse_length, ...
        'ModulationIndex',p.modulation_index, ...
        'WhitenStatus',p.whiten_status);
    cases(k)=struct('mode',p.mode,'channel_index',p.channel_index, ...
        'samples_per_symbol',p.samples_per_symbol, ...
        'pulse_length',p.pulse_length,'modulation_index',p.modulation_index, ...
        'whiten_status',p.whiten_status, ...
        'message',double(msg.'),'waveform_real',real(wave).', ...
        'waveform_imag',imag(wave).','bits',double(bits.'), ...
        'access_address',double(address.'));
end
fid=fopen(wt_sample_path('ble_coded_phy_samples.json'),'w','n','UTF-8');
fprintf(fid,'%s',jsonencode(cases)); fclose(fid);
end
