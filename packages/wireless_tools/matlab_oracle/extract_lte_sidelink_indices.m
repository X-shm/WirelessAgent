% Independent R2026a sidelink sync/control/shared RE positions.
root = fileparts(mfilename('fullpath'));
configs = {struct('NSLRB',15,'PRBSet',5,'SidelinkMode','D2D'),...
           struct('NSLRB',50,'PRBSet',13,'SidelinkMode','D2D',...
                  'CyclicPrefixSL','Extended'),...
           struct('NSLRB',50,'PRBSet',[5;6],'SidelinkMode','V2X')};
records = {};
for k = 1:numel(configs)
    ue = configs{k};
    [control,controlInfo] = ltePSCCHIndices(ue,{'1based','sub'});
    controlDrs = ltePSCCHDRSIndices(ue,{'1based','sub'});
    records{end+1} = struct('entry','ltePSCCHIndices','config',ue,...
        'indices',double(control),'info',controlInfo); %#ok<AGROW>
    records{end+1} = struct('entry','ltePSCCHDRSIndices','config',ue,...
        'indices',double(controlDrs)); %#ok<AGROW>
end
configs2 = {struct('NSLRB',50,'PRBSet',[30;31],...
                   'SidelinkMode','D2D','Modulation','QPSK'),...
            struct('NSLRB',15,'PRBSet',[3;4],...
                   'SidelinkMode','D2D','CyclicPrefixSL','Extended',...
                   'Modulation','16QAM'),...
            struct('NSLRB',50,'PRBSet',[30;31],...
                   'SidelinkMode','V2X','Modulation','QPSK')};
for k = 1:numel(configs2)
    ue = configs2{k};
    [shared,sharedInfo] = ltePSSCHIndices(ue,{'1based','sub'});
    sharedDrs = ltePSSCHDRSIndices(ue,{'1based','sub'});
    records{end+1} = struct('entry','ltePSSCHIndices','config',ue,...
        'indices',double(shared),'info',sharedInfo); %#ok<AGROW>
    records{end+1} = struct('entry','ltePSSCHDRSIndices','config',ue,...
        'indices',double(sharedDrs)); %#ok<AGROW>
end
for nrb = [6 50]
    for cp = {'Normal','Extended'}
        ue = struct('NSLRB',nrb,'CyclicPrefixSL',cp{1});
        positions = lteSSSSIndices(ue,{'1based','sub'});
        records{end+1} = struct('entry','lteSSSSIndices','config',ue,...
            'indices',double(positions)); %#ok<AGROW>
    end
end
output = fullfile(root,'samples','lte_sidelink_indices.json');
fid = fopen(output,'w');
fprintf(fid,'%s',jsonencode(records));
fclose(fid);
disp(output);
