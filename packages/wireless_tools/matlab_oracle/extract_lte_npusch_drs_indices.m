% Independent R2026a NPUSCH DRS FDD index cases for Python validation.
root = fileparts(mfilename('fullpath'));
ues = {struct('NBULSubcarrierSpacing','15kHz'),...
       struct('NBULSubcarrierSpacing','15kHz'),...
       struct('NBULSubcarrierSpacing','3.75kHz'),...
       struct('NBULSubcarrierSpacing','3.75kHz')};
channels = {struct('NPUSCHFormat','Data','NBULSubcarrierSet',[0 2 4]),...
            struct('NPUSCHFormat','Control','NBULSubcarrierSet',7),...
            struct('NPUSCHFormat','Data','NBULSubcarrierSet',33),...
            struct('NPUSCHFormat','Control','NBULSubcarrierSet',17)};
records = cell(1,numel(ues));
for k = 1:numel(ues)
    positions = lteNPUSCHDRSIndices(ues{k},channels{k},{'1based','sub'});
    records{k} = struct('ue',ues{k},'channel',channels{k},...
                        'indices',double(positions));
end
output = fullfile(root,'samples','lte_npusch_drs_indices.json');
fid = fopen(output,'w');
fprintf(fid,'%s',jsonencode(records));
fclose(fid);
disp(output);
