function gen_samples_ble_multipulse_receiver()
%GEN_SAMPLES_BLE_MULTIPULSE_RECEIVER R2026a uncoded pulse spans 2..4.
spec={ ...
    struct('mode','LE1M','channel_index',37,'samples_per_symbol',4, ...
        'pulse_length',2,'modulation_index',0.5,'message_length',35), ...
    struct('mode','LE2M','channel_index',8,'samples_per_symbol',8, ...
        'pulse_length',3,'modulation_index',0.48,'message_length',43), ...
    struct('mode','LE1M','channel_index',18,'samples_per_symbol',4, ...
        'pulse_length',4,'modulation_index',0.52,'message_length',51), ...
    struct('mode','LE2M','channel_index',2,'samples_per_symbol',4, ...
        'pulse_length',4,'modulation_index',0.5,'message_length',25)};
cases=struct('mode',{},'channel_index',{},'samples_per_symbol',{}, ...
    'pulse_length',{},'modulation_index',{},'message',{}, ...
    'waveform_real',{},'waveform_imag',{},'bits',{},'access_address',{});
for k=1:numel(spec)
    p=spec{k}; msg=mod((0:p.message_length-1)'+k,3)==0;
    wave=bleWaveformGenerator(msg,'Mode',p.mode, ...
        'ChannelIndex',p.channel_index, ...
        'SamplesPerSymbol',p.samples_per_symbol, ...
        'PulseLength',p.pulse_length, ...
        'ModulationIndex',p.modulation_index);
    [bits,address]=bleIdealReceiver(wave,'Mode',p.mode, ...
        'ChannelIndex',p.channel_index, ...
        'SamplesPerSymbol',p.samples_per_symbol, ...
        'PulseLength',p.pulse_length, ...
        'ModulationIndex',p.modulation_index);
    cases(k)=struct('mode',p.mode,'channel_index',p.channel_index, ...
        'samples_per_symbol',p.samples_per_symbol, ...
        'pulse_length',p.pulse_length,'modulation_index',p.modulation_index, ...
        'message',double(msg.'),'waveform_real',real(wave).', ...
        'waveform_imag',imag(wave).','bits',double(bits.'), ...
        'access_address',double(address.'));
end
fid=fopen(wt_sample_path('ble_multipulse_receiver_samples.json'),'w','n','UTF-8');
fprintf(fid,'%s',jsonencode(cases)); fclose(fid);
end
