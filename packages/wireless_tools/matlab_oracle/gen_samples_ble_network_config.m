function gen_samples_ble_network_config()
%GEN_SAMPLES_BLE_NETWORK_CONFIG Public defaults and override samples.
kinds={'bleCSConfig','bluetoothLEBIGConfig','bluetoothLECISConfig', ...
    'bluetoothLEConnectionConfig','bluetoothLEGAPConfig', ...
    'bluetoothLEPeriodicAdvConfig','bluetoothMeshFriendshipConfig', ...
    'bluetoothMeshProfileConfig'};
changes={ ...
    struct('StepMode',3,'Mode','LE2M','SequenceLength',32), ...
    struct('NumBIS',2), ...
    struct('MaxPDU',100), ...
    struct('PHYMode','LE2M','HopIncrement',9), ...
    struct('MaxConnections',10,'ScanWindow',0.025), ...
    struct('PHYMode','LE2M'), ...
    struct('ReceiveDelay',0.020), ...
    struct('Relay',true,'TTL',5)};
cases=struct('kind',{},'properties',{},'configuration',{});
for k=1:numel(kinds)
    for v=1:2
        cfg=feval(kinds{k});
        if v==1, overrides=struct(); else, overrides=changes{k}; end
        names=fieldnames(overrides);
        for n=1:numel(names), cfg.(names{n})=overrides.(names{n}); end
        names=properties(cfg); out=struct();
        for n=1:numel(names), out.(names{n})=cfg.(names{n}); end
        cases(end+1)=struct('kind',kinds{k},'properties',overrides, ...
            'configuration',out); %#ok<AGROW>
    end
end
fid=fopen(wt_sample_path('ble_network_config_samples.json'),'w','n','UTF-8');
fprintf(fid,'%s',jsonencode(cases)); fclose(fid);
end
