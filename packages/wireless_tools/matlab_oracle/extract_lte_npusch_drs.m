% Baseline NB-IoT NPUSCH Data DRS symbols with explicit slot state.
root = fileparts(mfilename('fullpath'));
records = {};
configs = {struct('spacing','15kHz','subcarriers',0,'slots',16), ...
           struct('spacing','15kHz','subcarriers',[0 2 4],'slots',8), ...
           struct('spacing','15kHz','subcarriers',0:11,'slots',2), ...
           struct('spacing','3.75kHz','subcarriers',17,'slots',16)};
for k = 1:numel(configs)
    cfg = configs{k};
    for cellid = [0 37]
        for slot = [0 1 7]
            ue = struct('NBULSubcarrierSpacing',cfg.spacing, ...
                'NNCellID',cellid,'NSlot',slot);
            chs = struct('NPUSCHFormat','Data', ...
                'NBULSubcarrierSet',cfg.subcarriers, ...
                'NRUsc',numel(cfg.subcarriers),'NRep',1,'NRU',1, ...
                'NULSlots',cfg.slots);
            [symbols,state] = lteNPUSCHDRS(ue,chs);
            records{end+1} = struct('spacing',cfg.spacing, ...
                'subcarriers',cfg.subcarriers,'ncellid',cellid, ...
                'slot',slot,'nul_slots',cfg.slots, ...
                'real',real(symbols(:)).','imag',imag(symbols(:)).', ...
                'state',state); %#ok<AGROW>
        end
    end
end
output = fullfile(root,'samples','lte_npusch_drs.json');
fid = fopen(output,'w');
assert(fid > 0);
fprintf(fid,'%s',jsonencode(records));
fclose(fid);
disp(output);
