function gen_samples_bluetooth_test_waveform()
%GEN_SAMPLES_BLUETOOTH_TEST_WAVEFORM LE1M/LE2M R2026a sample prefixes.
spec={struct('Mode','LE1M','PayloadLength',4,'PayloadType',0), ...
    struct('Mode','LE2M','PayloadLength',5,'PayloadType',3), ...
    struct('Mode','LE1M','PayloadLength',3,'PayloadType',1), ...
    struct('Mode','LE2M','PayloadLength',2,'PayloadType',7), ...
    struct('Mode','BR','PayloadType',1), ...
    struct('Mode','BR','PacketType','DM1','PayloadType',0), ...
    struct('Mode','BR','PacketType','DH3','PayloadType',2), ...
    struct('Mode','BR','PacketType','DM5','PayloadType',7), ...
    struct('Mode','LE125K','PayloadLength',4,'PayloadType',0), ...
    struct('Mode','LE500K','PayloadLength',5,'PayloadType',3), ...
    struct('Mode','LE125K','PayloadLength',2,'PayloadType',6), ...
    struct('Mode','LE1M','PayloadLength',2,'PayloadType',1, ...
        'PacketType','ConnectionCTE','CTELength',3), ...
    struct('Mode','LE2M','PayloadLength',3,'PayloadType',7, ...
        'PacketType','ConnectionCTE','CTELength',4,'CTEType',[0;1])};
cases=struct('properties',{},'samples',{},'waveform_real',{},'waveform_imag',{});
for k=1:numel(spec)
    p=spec{k}; cfg=bluetoothTestWaveformConfig;
    keys=fieldnames(p); for n=1:numel(keys), cfg.(keys{n})=p.(keys{n}); end
    wave=bluetoothTestWaveform(cfg);
    cases(k)=struct('properties',p,'samples',numel(wave), ...
        'waveform_real',real(wave(1:min(128,end))).', ...
        'waveform_imag',imag(wave(1:min(128,end))).');
end
fid=fopen(wt_sample_path('bluetooth_test_waveform_samples.json'),'w','n','UTF-8');
fprintf(fid,'%s',jsonencode(cases)); fclose(fid);
end
